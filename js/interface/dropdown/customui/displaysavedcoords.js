// Four readers of `savedViews` were deleted here: `getSavedView(query)`,
// `getSavedViews()`, `generateCopyPasteSavedViews()` and `listSavedViews()`. None had a
// live caller, and three of the four could not have worked if they had: `savedViews` is an
// object keyed by Fractal, so `savedViews.length` was always undefined and
// `savedViews.map` was a TypeError waiting for whoever uncommented the one call site.
// Write them again against the real shape if a caller ever needs them.

function receiveCurrentView() {
    return window.prompt("Enter a title for the current location:")
        .then( (title)=>(title === null ? null : {
                            title,
                            standardCoords: Graph.getCoords(),
                            functionCall: Graph.getCoords(true)
                        })
        )
        .catch(Logger.err.bind(Logger, "Failed to get prompt input:"))
}

let savedViews;

function updateSavedViewsCache() {
    localStorage.setItem('savedViews', JSON.stringify(savedViews));
}

function getSavedViewsFromCache() {
    const cachedViews = localStorage.getItem('savedViews');
    if (cachedViews) {
        const parsedViews = JSON.parse(cachedViews);
        // Check if the cached views have fractal types
        if (typeof parsedViews === 'object' && !Array.isArray(parsedViews)) {
            return parsedViews;
        }
    }

    return { ...defaultSavedViews };
}

function initializeSavedViews() {
    const cachedViews = getSavedViewsFromCache();
    savedViews = cachedViews ? cachedViews : { ...defaultSavedViews };
}

initializeSavedViews();

async function saveCurrentView() {
    const view = await receiveCurrentView();
    if (view === null) {
        Logger.info("View save cancelled by user.");
        return;
    }

    // Get the current fractal type from the dropdown
    const currentFractalType = Elem.byId('fractal-select').value;
    if (!savedViews[currentFractalType]) {
        savedViews[currentFractalType] = [];
    }
    savedViews[currentFractalType].push(view);
    Logger.info("View saved:", view.title);

    updateSavedViewsCache();
    displaySavedCoordinates();

    // Update button text temporarily
    const saveButton = Elem.byId('saveCoordinatesBtn');
    saveButton.textContent = "Saved!";
    const cb = ()=>{ saveButton.textContent = "Store View" } ;
    Promise.delay(500).then(cb);
}

On.change(Elem.byId('fractal-select'), displaySavedCoordinates);
On.click(Elem.byId('saveCoordinatesBtn'), saveCurrentView);

On.click(Elem.byId('deleteCoordinatesBtn'), (e) => {
    if (Coordinate.selectedView) {
        deleteSavedView(Coordinate.selectedView);
    } else {
        alert('No saved view is selected.');
    }
});

// Which list actually holds it. `savedViews` is keyed by fractal, plus an `all` for the
// views that make sense under any of them, and the strip on screen is two of those lists
// end to end -- so the only reliable answer is to look.
function listHoldingView(view) {
    for (const fractalType in savedViews) {
        const views = savedViews[fractalType];
        if (Array.isArray(views) && views.includes(view)) return views;
    }
    return null;
}

function deleteSavedView(view) {
    const views = listHoldingView(view);
    if (!views) {
        Logger.err("No saved view to delete:", view);
        return;
    }

    views.splice(views.indexOf(view), 1);

    updateSavedViewsCache();
    displaySavedCoordinates();

    Logger.info("View deleted:", view.title);

    Coordinate.resetSelected();
}

function returnToSavedView(savedView, animate = true, speed = 0.0001) {
    const standardCoords = savedView?.standardCoords;
    if (!standardCoords) {
        Logger.info("Missing or invalid saved view:", savedView);
        return;
    }

    // Extract real and imaginary parts from pan
    const panParts = standardCoords.pan.split('+i');
    const panReal = parseFloat(panParts[0]);
    const panImaginary = panParts.length > 1 ? parseFloat(panParts[1]) : 0;

    Animation.goToCoords(
        parseFloat(standardCoords.zoom),
        panReal,
        panImaginary,
        animate,
        speed
    );
}



// The selection is the view object, not its position. Position was the bug: the strip
// on screen is the current fractal's views followed by `savedViews.all`, so an index
// into what the reader sees is an index into neither array -- and `deleteSavedView`
// spliced the per-fractal one with it. Selecting `// Reset View`, which lives in `all`,
// deleted whatever mandelbrot view happened to sit at that position.
const Coordinate = {
    selectedDiv: null,
    selectedView: null
}
Coordinate.deselect = function () {
    if (!this.selectedDiv) return;

    this.selectedDiv.classList.remove('selected-coordinate');
    this.resetSelected();
}
Coordinate.resetSelected = function () {
    this.selectedDiv = null;
    this.selectedView = null;
}

function appendViewsToContainer(views, containerId) {
    const container = Elem.byId(containerId);
    container.innerHTML = '';

    views.forEach((view) => {
        const coordElement = Html.make.div('saved-coordinate-item');
        coordElement.textContent = view.title;

        On.click(coordElement, (e) => {
            returnToSavedView(view);

            // Update selected state
            document.querySelectorAll('.saved-coordinate-item').forEach(div => {
                div.classList.remove('selected-coordinate');
                div.style.transform = '';
            });

            coordElement.classList.add('selected-coordinate');
            coordElement.style.transform = 'scale(0.95)'; // Scale down for selected
            Coordinate.selectedDiv = coordElement;
            Coordinate.selectedView = view;
        });

        // Reset the scale when mouse leaves the selected item
        On.mouseleave(coordElement, (e) => {
            if (coordElement.classList.contains('selected-coordinate')) {
                coordElement.style.transform = 'scale(1)';
            }
        });

        container.appendChild(coordElement);
    });
}

function displaySavedCoordinates() {
    // The module's own `savedViews`, not a fresh parse of the cache. It used to shadow the
    // name with `getSavedViewsFromCache()`, which returns new objects every call -- so a
    // rendered element held a copy that no list in memory contained, and deleting by
    // identity could not find it. `localStorage` is the mirror here, written by
    // `updateSavedViewsCache` and read once at load; nothing else writes the key.
    const currentFractalType = Elem.byId('fractal-select').value;
    const currentFractalViews = savedViews[currentFractalType] || [];
    const allViews = savedViews.all || [];
    const combinedViews = [...currentFractalViews, ...allViews];

    // One container that wraps. It was three, of fixed height, fed by a
    // `distributeCoordinates` that sliced the list 50% / 32% / the rest -- so the places
    // read out of order with dead bands between them, and the first container was
    // indented 100px to clear a `position: fixed` column of buttons that no longer
    // exists. The split was never about the places; it was about fitting around the
    // saves panel they used to share.
    appendViewsToContainer(combinedViews, 'savedCoordinatesContainer');
}
